"""Optional real PG restore test; only a new loopback cluster with fake data.

FAEHUB_PG_TEST_BIN points to official portable Postgres tools. No app/cloud
connection is read, and no Windows service is installed.
"""
import base64
import os
from pathlib import Path
import socket
import subprocess
import tempfile
import unittest
from unittest.mock import patch

import psycopg
from cryptography.fernet import Fernet
import backup_service as backup


@unittest.skipUnless(os.getenv('FAEHUB_PG_TEST_BIN'),'Optional portable PostgreSQL test runtime not configured')
class PostgreSQLBackupTests(unittest.TestCase):
    def test_real_dump_encryption_restore_attachment_and_empty_destination_guard(self):
        pg_bin=Path(os.environ['FAEHUB_PG_TEST_BIN']).resolve()
        with tempfile.TemporaryDirectory(prefix='faehub-pg-backup-test-') as scratch:
            folder=Path(scratch);data=folder/'cluster';log=folder/'server.log'
            def run(name,*args):
                # A detached Windows postgres process can inherit pipe handles
                # from pg_ctl and keep communicate() waiting after pg_ctl exits.
                result=subprocess.run([str(pg_bin/(name+'.exe' if os.name=='nt' else name)),*map(str,args)],
                                      stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL,timeout=60)
                self.assertEqual(result.returncode,0,'Disposable PostgreSQL command failed: '+name)
            run('initdb','-D',data,'-U','faehub_fixture','-A','trust','--no-locale','-E','UTF8')
            with socket.socket() as sock:
                sock.bind(('127.0.0.1',0));port=sock.getsockname()[1]
            try:
                run('pg_ctl','-D',data,'-l',log,'-o',f'-p {port} -h 127.0.0.1','-w','start')
                origin=f'postgresql://faehub_fixture@127.0.0.1:{port}/backup_source'
                target=f'postgresql://faehub_fixture@127.0.0.1:{port}/backup_target'
                with psycopg.connect(f'postgresql://faehub_fixture@127.0.0.1:{port}/postgres',autocommit=True) as conn:
                    conn.execute('CREATE DATABASE backup_source');conn.execute('CREATE DATABASE backup_target')
                protector=Fernet.generate_key();totp_secret=b'DISPOSABLE-AUTHENTICATOR-SECRET'
                ciphertext=Fernet(protector).encrypt(totp_secret).decode()
                attachment=b'disposable attachment bytes\x00\xff'
                with psycopg.connect(origin) as conn:
                    conn.execute('CREATE TABLE users(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name text)')
                    conn.execute('CREATE TABLE file_attachments(id bigint PRIMARY KEY,owner_id bigint REFERENCES users(id),content bytea)')
                    conn.execute('CREATE TABLE account_mfa(user_id bigint PRIMARY KEY REFERENCES users(id),secret_ciphertext text)')
                    conn.execute("INSERT INTO users(name) VALUES('Pessoa Teste')")
                    conn.execute('INSERT INTO file_attachments VALUES(1,1,%s)',(attachment,))
                    conn.execute('INSERT INTO account_mfa VALUES(1,%s)',(ciphertext,))
                    conn.execute('ALTER TABLE account_mfa ENABLE ROW LEVEL SECURITY')
                with patch.dict(os.environ,{'PATH':str(pg_bin)+os.pathsep+os.environ.get('PATH',''),
                        'FAEHUB_BACKUP_KEY':base64.urlsafe_b64encode(os.urandom(32)).decode()}):
                    path=backup.create_backup(folder,origin)
                    self.assertTrue(path.exists());self.assertNotIn(attachment,path.read_bytes())
                    actual_run=subprocess.run
                    def fixture_run(*args,**kwargs):
                        result=actual_run(*args,**kwargs)
                        # Only this isolated fictional fixture may reveal diagnostics.
                        self.assertEqual(result.returncode,0,result.stderr.decode(errors='replace'))
                        return result
                    with patch.object(backup.subprocess,'run',side_effect=fixture_run):
                        manifest=backup.restore_to_empty(path,target,origin)
                    self.assertEqual(manifest['tables'],dict(users=1,file_attachments=1,account_mfa=1))
                    with psycopg.connect(target) as conn:
                        self.assertEqual(bytes(conn.execute('SELECT content FROM file_attachments').fetchone()[0]),attachment)
                        self.assertEqual(Fernet(protector).decrypt(conn.execute('SELECT secret_ciphertext FROM account_mfa').fetchone()[0].encode()),totp_secret)
                        self.assertTrue(conn.execute("SELECT relrowsecurity FROM pg_class WHERE relname='account_mfa'").fetchone()[0])
                        self.assertEqual(conn.execute("INSERT INTO users(name) VALUES('Outra Pessoa') RETURNING id").fetchone()[0],2)
                    with self.assertRaisesRegex(ValueError,'vazio'):backup.restore_to_empty(path,target,origin)
            finally:
                if (data/'postmaster.pid').exists():
                    run('pg_ctl','-D',data,'-m','fast','-w','stop')


if __name__=='__main__':unittest.main()
